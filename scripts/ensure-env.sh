#!/usr/bin/env bash
# Create .env from .env.example if missing and fill an empty BYOP_SECRET_KEY.
set -euo pipefail

cd "$(dirname "$0")/.."

[ -f .env ] || cp .env.example .env

if grep -qE '^BYOP_SECRET_KEY=$' .env; then
  key=$(openssl rand -hex 32)
  tmp=$(mktemp)
  awk -v k="$key" '/^BYOP_SECRET_KEY=$/ { print "BYOP_SECRET_KEY=" k; next } { print }' .env > "$tmp"
  cat "$tmp" > .env
  rm -f "$tmp"
  echo "Generated BYOP_SECRET_KEY in .env"
fi
